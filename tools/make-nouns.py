#!/usr/bin/env python3
"""Derive the noun bank embedded in demo-genre.html from Lexique 4.1.

The codex never learned French. The gender drill is the single exception ADR
0003 allows: a fixed, frequency-ordered list of nouns, each carrying exactly one
gender. This script is the only place that list is derived — the demo keeps a
copy inline, and the app version will be generated by the same rules.

Filter, in order:

  * `5_Cgram == NOM` and `14_IsLem == 1` — noun lemmas only, not their forms;
  * `7_Genre` is `m` or `f` — the drill asks exactly one question;
  * `8_Nombre` is not `p` — les gens is not a le/la question;
  * the first letter takes no elision (`l'`) — «la eau» is not French, and an
    article that is not le/la cannot be the answer to a le/la question;
  * a strict alphabet — abbreviations and loanwords (`t.`, `p.m.`, `señor`)
    are not drill material.

The top `--count` survivors by `12_FreqLemme` become the bank. Sorted by
frequency, with the lemma breaking ties, so the same input yields the same
bank.

Every noun carries its gender and, when `--glosses` is given, the one-line
Chinese gloss kept in `tools/nouns-glosses.json`: the drill shows the French
and the Chinese together, so the word is recognised and only the gender is
asked.

Usage:
    python tools/make-nouns.py                                          # JSON to stdout
    python tools/make-nouns.py --js                                     # `const NOUNS = [...];`
    python tools/make-nouns.py --glosses tools/nouns-glosses.json --js  # what the demo embeds
    python tools/make-nouns.py --out nouns.json                         # write to a file
"""

import argparse
import csv
import json
import re
import sys

DEFAULT_TSV = r"C:\Users\jason\Downloads\Lexique4.1\Lexique4.1.tsv"

# A noun opening with one of these wears l', which hides the gender the drill
# is asking about — so it is not a le/la noun phase.
ELISION_INITIALS = frozenset("aàâäeéèêëiîïoôöuùûüœæyh")

# Letters, plus the apostrophe and hyphen a French lemma may carry. A space is
# allowed for compounds (pomme de terre); digits, dots and tildes are not.
WORD = re.compile(r"^[a-zàâäéèêëîïôöùûüœæç][a-zàâäéèêëîïôöùûüœæç' -]*$")

# Lexique files grammatical words, numerals and adjective lemmas under NOM too;
# a le/la question about them teaches nothing. Curated by eye over the top of
# the frequency list — a frequency rank is not a quality rank.
STOPWORDS = frozenset(
    {
        # grammatical words and bound forms
        "par", "pour", "plus", "moi", "dire", "semblant", "cesse", "min",
        "mme", "mlle", "neuf",
        # English loans with no settled everyday use as French nouns
        "to", "go", "by", "no", "for", "rob", "boy", "lady", "miss", "show",
        "team", "business", "major", "top", "stop", "baby",
        # numerals used as nouns
        "deux", "trois", "quatre", "cinq", "mille",
        # adjective lemmas whose NOM entry is the adjective over again
        "beau", "bon", "vrai", "seul", "commun", "double", "grand", "petit",
        "premier", "meilleur", "mieux", "gros", "long", "dur", "frais",
        "fraîche", "blanc", "noir", "rouge", "bleu", "super", "prochain",
        "suivant",
    }
)

# Lexique writes the oe ligature as two letters; the drill shows the word a
# learner will actually meet in print.
DISPLAY = {"coeur": "cœur", "voeu": "vœu"}



def read_candidates(tsv):
    """Yield (frequency, lemma, gender) for every noun the drill could use."""
    with open(tsv, encoding="utf-8", errors="replace", newline="") as handle:
        reader = csv.reader(handle, delimiter="\t")
        header = next(reader)
        column = {name.strip(): index for index, name in enumerate(header)}

        def cell(row, name):
            index = column[name]
            return row[index].strip() if index < len(row) else ""

        for row in reader:
            if cell(row, "5_Cgram") != "NOM" or cell(row, "14_IsLem") != "1":
                continue
            gender = cell(row, "7_Genre")
            if gender not in ("m", "f"):
                continue
            if cell(row, "8_Nombre") == "p":
                continue
            lemma = cell(row, "4_Lemme")
            if not lemma or lemma[0].lower() in ELISION_INITIALS:
                continue
            if len(lemma) < 2 or lemma in STOPWORDS:
                continue
            if not WORD.match(lemma):
                continue
            try:
                frequency = float(cell(row, "12_FreqLemme"))
            except ValueError:
                continue
            yield frequency, lemma, gender


def build(tsv, count):
    # Lexique lists a lemma once per form; keep the highest frequency per
    # lemma so the bank has one row per noun.
    best = {}
    for frequency, lemma, gender in read_candidates(tsv):
        seen = best.get(lemma)
        if seen is None or frequency > seen[0]:
            best[lemma] = (frequency, gender)

    ranked = sorted(best.items(), key=lambda item: (-item[1][0], item[0]))
    if len(ranked) < count:
        raise SystemExit(
            f"only {len(ranked)} usable nouns, {count} requested"
        )

    return [
        {"w": DISPLAY.get(lemma, lemma), "g": gender, "f": round(frequency, 2)}
        for lemma, (frequency, gender) in ranked[:count]
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tsv", default=DEFAULT_TSV, help="Lexique 4.1 TSV")
    parser.add_argument("--count", type=int, default=1000)
    parser.add_argument("--out", help="write the JSON to this file instead of stdout")
    parser.add_argument(
        "--js",
        action="store_true",
        help="wrap the JSON as a `const NOUNS = ...;` declaration",
    )
    parser.add_argument(
        "--glosses",
        help="JSON object {word: chinese gloss} to merge in as each noun's `zh`",
    )
    args = parser.parse_args()

    bank = build(args.tsv, args.count)

    if args.glosses:
        with open(args.glosses, encoding="utf-8") as handle:
            glosses = json.load(handle)
        missing = [noun["w"] for noun in bank if noun["w"] not in glosses]
        if missing:
            raise SystemExit(
                f"missing glosses for {len(missing)} nouns, e.g. {missing[:8]}"
            )
        for noun in bank:
            noun["zh"] = glosses[noun["w"]]
    payload = json.dumps(bank, ensure_ascii=False, separators=(",", ":"))
    if args.js:
        payload = "const NOUNS = " + payload + ";"

    masculine = sum(1 for noun in bank if noun["g"] == "m")
    words = {noun["w"] for noun in bank}
    if len(words) != len(bank):
        raise SystemExit(f"duplicate lemma in the bank: {len(bank) - len(words)}")
    print(
        f"{len(bank)} nouns — m/f {masculine}/{len(bank) - masculine}, "
        f"min freq {bank[-1]['f']}, elision-free, le/la only",
        file=sys.stderr,
    )

    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(payload + "\n")
    else:
        print(payload)


if __name__ == "__main__":
    main()
